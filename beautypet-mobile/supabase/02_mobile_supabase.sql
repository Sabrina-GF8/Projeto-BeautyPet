-- 3) Quando uma conta é criada no Supabase Auth, vincula pelo e-mail a ficha WEB.
--    Se a ficha não existir, cria uma nova ficha simplificada.
CREATE OR REPLACE FUNCTION public.handle_new_mobile_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_cliente_id BIGINT;
    v_nome TEXT;
BEGIN
    v_nome := COALESCE(
        NULLIF(TRIM(NEW.raw_user_meta_data ->> 'nome'), ''),
        NULLIF(SPLIT_PART(COALESCE(NEW.email, ''), '@', 1), ''),
        'Tutor'
    );

    UPDATE public.clientes
       SET auth_user_id = NEW.id,
           email = COALESCE(email, NEW.email)
     WHERE LOWER(COALESCE(email, '')) = LOWER(COALESCE(NEW.email, ''))
       AND (auth_user_id IS NULL OR auth_user_id = NEW.id)
     RETURNING id INTO v_cliente_id;

    IF v_cliente_id IS NULL THEN
        INSERT INTO public.clientes (
            auth_user_id,
            nome,
            email,
            telefone_principal,
            ativo
        )
        VALUES (
            NEW.id,
            v_nome,
            NEW.email,
            '',
            TRUE
        )
        RETURNING id INTO v_cliente_id;
    END IF;

    RETURN NEW;
END;
$$;


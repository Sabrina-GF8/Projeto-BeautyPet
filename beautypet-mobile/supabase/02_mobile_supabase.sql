-- 2) Função que retorna o cliente correspondente ao usuário autenticado.
CREATE OR REPLACE FUNCTION public.fn_mobile_cliente_id_atual()
RETURNS BIGINT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
    SELECT c.id::BIGINT
    FROM public.clientes c
    WHERE c.auth_user_id = auth.uid()
      AND c.ativo = TRUE
    LIMIT 1;
$$;


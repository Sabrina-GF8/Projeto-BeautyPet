-- 10) Função segura que calcula os horários livres de banho/tosa.
--     O app recebe apenas horários; os agendamentos de outros tutores não são expostos.
CREATE OR REPLACE FUNCTION public.fn_mobile_horarios_disponiveis(
    p_data DATE,
    p_servico_ids BIGINT[],
    p_duracao_minutos INTEGER DEFAULT 60
)
RETURNS TABLE (horario TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_eh_banho_tosa BOOLEAN;
    v_padrao_id BIGINT;
    v_blocos INTEGER;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado.';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM public.servicos s
        JOIN public.categorias_servico cs ON cs.id = s.categoria_id
        WHERE s.id = ANY(p_servico_ids)
          AND s.ativo = TRUE
          AND (
              LOWER(cs.nome) LIKE '%banho%'
              OR LOWER(cs.nome) LIKE '%tosa%'
              OR LOWER(s.nome) LIKE '%banho%'
              OR LOWER(s.nome) LIKE '%tosa%'
              OR LOWER(s.nome) LIKE '%higien%'
          )
    ) INTO v_eh_banho_tosa;

    IF NOT v_eh_banho_tosa THEN
        RETURN QUERY
        SELECT v.h
        FROM (VALUES
            ('09:00'), ('10:00'), ('11:00'),
            ('12:00'), ('14:00'), ('16:00')
        ) AS v(h);
        RETURN;
    END IF;

    SELECT ap.id
      INTO v_padrao_id
      FROM public.agenda_padrao_banho_tosa ap
     WHERE ap.ativo = TRUE
       AND ap.dia_semana = EXTRACT(ISODOW FROM p_data)::INTEGER
       AND ap.data_inicio <= p_data
       AND (
            ap.tipo_duracao = 'INDETERMINADO'
            OR ap.data_fim >= p_data
       )
     ORDER BY ap.data_inicio DESC, ap.id DESC
     LIMIT 1;

    IF v_padrao_id IS NULL THEN
        RETURN;
    END IF;

    v_blocos := GREATEST(1, CEIL(GREATEST(p_duracao_minutos, 30) / 30.0)::INTEGER);

    RETURN QUERY
    WITH slots AS (
        SELECT
            h.horario,
            h.quantidade_vagas,
            ROW_NUMBER() OVER (ORDER BY h.horario) AS rn
        FROM public.agenda_padrao_banho_tosa_horarios h
        WHERE h.agenda_padrao_id = v_padrao_id
    ),
    ocupacao AS (
        SELECT
            s.horario,
            COUNT(DISTINCT a.id)::INTEGER AS quantidade_ocupada
        FROM slots s
        LEFT JOIN public.agendamentos a
          ON a.status NOT IN ('CANCELADO', 'RECUSADO')
         AND a.data_hora_inicio::DATE = p_data
         AND a.data_hora_inicio < (p_data + s.horario + INTERVAL '30 minutes')
         AND COALESCE(a.data_hora_fim, a.data_hora_inicio + INTERVAL '30 minutes')
             > (p_data + s.horario)
         AND EXISTS (
             SELECT 1
             FROM public.agendamento_itens ai
             JOIN public.servicos sv ON sv.id = ai.servico_id
             JOIN public.categorias_servico cs ON cs.id = sv.categoria_id
             WHERE ai.agendamento_id = a.id
               AND (
                   LOWER(cs.nome) LIKE '%banho%'
                   OR LOWER(cs.nome) LIKE '%tosa%'
                   OR LOWER(sv.nome) LIKE '%banho%'
                   OR LOWER(sv.nome) LIKE '%tosa%'
                   OR LOWER(sv.nome) LIKE '%higien%'
               )
         )
        GROUP BY s.horario
    )
    SELECT TO_CHAR(base.horario, 'HH24:MI')
    FROM slots base
    WHERE NOT EXISTS (
        SELECT 1
        FROM generate_series(0, v_blocos - 1) AS g(bloco)
        LEFT JOIN slots atual
          ON atual.rn = base.rn + g.bloco
        LEFT JOIN ocupacao o
          ON o.horario = atual.horario
        WHERE atual.rn IS NULL
           OR atual.horario <> base.horario + (g.bloco * INTERVAL '30 minutes')
           OR atual.quantidade_vagas - COALESCE(o.quantidade_ocupada, 0) <= 0
    )
    ORDER BY base.horario;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_mobile_horarios_disponiveis(DATE, BIGINT[], INTEGER) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_mobile_horarios_disponiveis(DATE, BIGINT[], INTEGER) TO authenticated;

